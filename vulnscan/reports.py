"""Report export (FR-19): PDF via ReportLab, self-contained HTML, and JSON.

`scan` is a history record: {id, target, profile, context, created_at,
finished_at, result}. `profile` is the profile's config entry."""
import html
import json

from .pipeline import PRIORITY_ORDER, SEVERITY_ORDER, coverage_rows, flat_findings

SENSITIVITY_NOTE = (
    "CONFIDENTIAL: this report lists exploitable weaknesses and asset details. "
    "Store it securely and share it only with people authorised to see it."
)
DISCLAIMER = (
    "Findings are based on service version fingerprinting and public NVD data and "
    "should be verified before remediation. AI-generated recommendations are advisory; "
    "check them against the linked NVD record. Only scan systems you are authorised to test."
)
SOURCE_LABEL = {
    "ai": "AI-generated, verify against NVD",
    "demo": "Sample data",
    "engine": "Generated by mitigation engine",
    "fallback": "No validated recommendation",
}
SEV_HEX = {"CRITICAL": "#b42318", "HIGH": "#d9480f", "MEDIUM": "#b7791f",
           "LOW": "#2f6fb3", "NONE": "#6b7280"}
PRIO_HEX = {"P1": "#b42318", "P2": "#d9480f", "P3": "#b7791f", "P4": "#2f6fb3"}


def _e(value) -> str:
    return html.escape(str(value if value is not None else ""))


def _when(ts) -> str:
    return (ts or "").replace("T", " ")


def source_text(m) -> str:
    """'AI-generated (gemini-3.8-flash), verify...' or the fallback reason."""
    if m.get("source") == "ai" and m.get("model"):
        return f"AI-generated by {m['model']}, verify against NVD"
    if m.get("note"):
        return m["note"]
    return SOURCE_LABEL.get(m.get("source"), m.get("source", ""))


def _data_source(result) -> str:
    if result.get("backend") == "demo":
        return "DEMO SAMPLE DATA (not a real scan)"
    return "Live scan (Nmap + NVD)"


def _os_lines(result) -> str:
    return "; ".join(f"{h['ip']}: {h['os']}" for h in result.get("hosts", []) if h.get("os"))


def _cvss_label(f) -> str:
    if f.get("scored") is False:
        return "not yet scored by NVD"
    return f"{f['severity']} / CVSS {f['cvss']} (v{f['cvss_version']})"


def _service_label(f) -> str:
    return f"{f.get('product', '')} {f.get('version', '')}".strip() or f.get("service", "")


def executive_summary(result) -> str:
    s = result["summary"]
    if not s["cves"]:
        text = (f"No known vulnerabilities were matched to the {s['assessed']} assessed "
                f"service(s).")
    else:
        sev = ", ".join(f"{s['by_severity'][k]} {k.lower()}" for k in SEVERITY_ORDER
                        if s["by_severity"].get(k))
        t = s["top_finding"]
        text = (f"The scan found {s['cves']} known vulnerabilities ({sev}) across "
                f"{s['open_ports']} open ports. The most urgent issue is {t['id']} in "
                f"{t['service']} on port {t['port']} ({t['priority']}, risk "
                f"{t['risk_score']}/10).")
    if not s["complete"]:
        text += (f" The assessment is incomplete: {s['not_assessed']} service(s) could not "
                 f"be assessed, so absence of findings there does not mean they are safe.")
    return text


# --------------------------------------------------------------------------
# JSON
# --------------------------------------------------------------------------
def write_json(scan, path) -> None:
    payload = {k: scan.get(k) for k in
               ("id", "target", "profile", "context", "created_at", "finished_at", "result")}
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2)


