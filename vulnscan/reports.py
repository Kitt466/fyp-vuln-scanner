def _pill(text, color) -> str:
    return f'<span class="pill" style="background:{color}">{_e(text)}</span>'


def build_html(scan, profile) -> str:
    r = scan["result"]
    s = r["summary"]
    ctx = scan["context"]
    out = [
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>",
        "<meta name='viewport' content='width=device-width,initial-scale=1'>",
        f"<title>Vulnerability Assessment Report - {_e(scan['target'])}</title>",
        f"<style>{_CSS}</style></head><body><div class='page'>",
        "<h1>Vulnerability Assessment Report</h1>",
        "<div class='muted'>Automated Vulnerability Scanner for Service Detection and "
        "CVE Analysis with Suggested Mitigation</div>",
        f"<div class='conf'>{_e(SENSITIVITY_NOTE)}</div>",
        "<dl>",
        f"<dt>Target</dt><dd class='mono'>{_e(scan['target'])}</dd>",
        f"<dt>Asset</dt><dd>{_e(ctx.get('asset_name') or '-')}</dd>",
        f"<dt>Business function</dt><dd>{_e(ctx.get('business_function') or '-')}</dd>",
        f"<dt>Scan profile</dt><dd>{_e(profile.get('label', scan['profile']))} "
        f"<span class='mono muted'>(nmap {_e(profile.get('args', ''))})</span></dd>",
        f"<dt>Data source</dt><dd>{_e(_data_source(r))}</dd>",
        (f"<dt>OS detection</dt><dd>{_e(_os_lines(r))}</dd>" if _os_lines(r) else ""),
        f"<dt>Started</dt><dd>{_e(_when(scan.get('created_at')))}</dd>",
        f"<dt>Completed</dt><dd>{_e(_when(scan.get('finished_at')))}</dd>",
        f"<dt>Scan ID</dt><dd class='mono'>{_e(scan['id'])}</dd></dl>",
        "<h2>1. Executive summary</h2><div class='kpis'>",
        f"<div class='kpi'><b>{s['open_ports']}</b><span>Open ports</span></div>",
        f"<div class='kpi'><b>{s['assessed']}/{s['open_ports']}</b><span>Assessed</span></div>",
        f"<div class='kpi'><b>{s['cves']}</b><span>CVEs</span></div>",
        f"<div class='kpi'><b>{_e(s['top_finding']['priority'] if s['top_finding'] else '-')}"
        f"</b><span>Highest priority</span></div></div>",
        f"<p>{_e(executive_summary(r))}</p>",
    ]
    if not s["complete"]:
        out.append(f"<div class='warn'><b>Incomplete assessment.</b> {s['not_assessed']} "
                   f"service(s) were not assessed. See section 3.</div>")

    out += [
        "<h2>2. Asset context and scoring</h2><table>",
        f"<tr><th>Criticality</th><td>{_e(ctx.get('criticality', 'medium').capitalize())}</td></tr>",
        f"<tr><th>Internet-facing</th><td>{'Yes' if ctx.get('internet_facing') else 'No'}</td></tr>",
        f"<tr><th>Stores sensitive data</th><td>{'Yes' if ctx.get('sensitive_data') else 'No'}</td></tr>",
        "</table><p class='muted'>Risk score = CVSS base score adjusted for internet exposure, "
        "data sensitivity and business criticality (capped at 10). Priority: P1 &ge; 9.0, "
        "P2 &ge; 7.0, P3 &ge; 4.0, P4 below 4.0. Detection confidence is reported separately: "
        "High = product and version identified, Medium = product only or keyword match, "
        "Low = service name only.</p>",
        "<h2>3. Assessment coverage</h2><table><thead><tr><th>Host</th><th>Port</th>"
        "<th>Service</th><th>Product / version</th><th>Status</th><th>CVEs</th></tr></thead><tbody>",
    ]
    for c in coverage_rows(r):
        status = "Assessed" if c["assessed"] else f"Not assessed: {c['reason']}"
        out.append(
            f"<tr><td class='mono'>{_e(c['host'])}</td><td class='mono'>{c['port']}/"
            f"{_e(c['protocol'])}</td><td>{_e(c['service'])}</td>"
            f"<td>{_e((c['product'] + ' ' + c['version']).strip() or '-')}</td>"
            f"<td>{_e(status)}</td><td>{c['cves'] if c['assessed'] else '-'}</td></tr>")
    out.append("</tbody></table>")

    out.append("<h2>4. Findings and recommendations</h2>")
    findings = flat_findings(r)
    if not findings:
        out.append("<p>No findings.</p>")
    for n, f in enumerate(findings, 1):
        m = f["mitigation"]
        steps = "".join(f"<li>{_e(x)}</li>" for x in m["steps"])
        refs = " ".join(f"<span class='mono'>{_e(x)}</span>" for x in m["references"])
        out.append(
            f"<div class='f' style='border-left-color:{PRIO_HEX.get(f['priority'], '#6b7280')}'>"
            f"<h3><span>{n}.</span><span class='mono'>{_e(f['id'])}</span>"
            f"{_pill(f['priority'], PRIO_HEX.get(f['priority'], '#6b7280'))}"
            f"{_pill(_cvss_label(f), SEV_HEX.get(f['severity'], '#6b7280'))}"
            f"</h3><div class='muted mono'>{_e(f['host'])}:{f['port']}/{_e(f['protocol'])} | "
            f"{_e(_service_label(f))} | risk {f['risk_score']}/10 | confidence "
            f"{_e(f['confidence'])}{' (keyword match)' if f['match_method'] == 'keyword' else ''}</div>"
            f"<p>{_e(f['description'])}</p>"
            f"<div class='mit'><b>Recommendation:</b> {_e(m['summary'])}"
            f"{'<ol>' + steps + '</ol>' if steps else ''}</div>"
            f"<div class='src'>{_e(source_text(m))} | {refs}</div></div>")

    out.append(f"<div class='foot'>{_e(DISCLAIMER)}</div></div></body></html>")
    return "".join(out)


def write_html(scan, profile, path) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(build_html(scan, profile))


# --------------------------------------------------------------------------
# PDF (ReportLab)
# --------------------------------------------------------------------------
def write_pdf(scan, profile, path) -> None:
    try:
        from reportlab.lib import colors
        from reportlab.lib.enums import TA_LEFT
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import (KeepTogether, Paragraph, SimpleDocTemplate,
                                        Spacer, Table, TableStyle)
    except ImportError as exc:
        raise RuntimeError("PDF export needs ReportLab: pip install reportlab") from exc

    r = scan["result"]
    s = r["summary"]
    ctx = scan["context"]
    base = getSampleStyleSheet()
    st = {
        "title": ParagraphStyle("t", parent=base["Title"], fontSize=20, alignment=TA_LEFT,
                                spaceAfter=2),
        "sub": ParagraphStyle("s", parent=base["Normal"], textColor=colors.HexColor("#5b6470")),
        "h2": ParagraphStyle("h2", parent=base["Heading2"], fontSize=13, spaceBefore=14,
                             spaceAfter=6),
        "body": ParagraphStyle("b", parent=base["Normal"], fontSize=9.5, leading=13),
        "small": ParagraphStyle("sm", parent=base["Normal"], fontSize=8, leading=10.5,
                                textColor=colors.HexColor("#5b6470")),
        "cell": ParagraphStyle("c", parent=base["Normal"], fontSize=8.5, leading=11),
        "conf": ParagraphStyle("cf", parent=base["Normal"], fontSize=8.5, leading=11,
                               backColor=colors.HexColor("#fff4e5"), borderPadding=6,
                               borderColor=colors.HexColor("#f0c27b"), borderWidth=0.6),
    }
    grid = TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d9dee4")),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f3f5f7")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
    ])

    def P(text, style="cell"):
        return Paragraph(_e(text), st[style])

    story = [
        Paragraph("Vulnerability Assessment Report", st["title"]),
        Paragraph("Automated Vulnerability Scanner for Service Detection and CVE "
                  "Analysis with Suggested Mitigation", st["sub"]),
        Spacer(1, 6 * mm),
        Paragraph(_e(SENSITIVITY_NOTE), st["conf"]),
        Spacer(1, 5 * mm),
    ]
    meta = [
        ["Target", scan["target"]],
        ["Asset", ctx.get("asset_name") or "-"],
        ["Business function", ctx.get("business_function") or "-"],
        ["Scan profile", f"{profile.get('label', scan['profile'])} (nmap {profile.get('args', '')})"],
        ["Data source", _data_source(r)],
    ] + ([["OS detection", _os_lines(r)]] if _os_lines(r) else []) + [
        ["Started", _when(scan.get("created_at"))],
        ["Completed", _when(scan.get("finished_at"))],
        ["Scan ID", scan["id"]],
    ]
    t = Table([[P(a), P(b)] for a, b in meta], colWidths=[40 * mm, 130 * mm])
    t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                           ("LINEBELOW", (0, 0), (-1, -1), 0.3, colors.HexColor("#d9dee4"))]))
    story += [t, Paragraph("1. Executive summary", st["h2"]),
              Paragraph(_e(executive_summary(r)), st["body"])]

    kpi = Table([[P("Open ports"), P("Assessed"), P("CVEs"), P("Highest priority")],
                 [P(s["open_ports"]), P(f"{s['assessed']}/{s['open_ports']}"), P(s["cves"]),
                  P(s["top_finding"]["priority"] if s["top_finding"] else "-")]],
                colWidths=[42.5 * mm] * 4)
    kpi.setStyle(grid)
    story += [Spacer(1, 3 * mm), kpi]

    story += [
        Paragraph("2. Asset context and scoring", st["h2"]),
        Paragraph(_e(f"Criticality: {ctx.get('criticality', 'medium').capitalize()} | "
                     f"Internet-facing: {'Yes' if ctx.get('internet_facing') else 'No'} | "
                     f"Sensitive data: {'Yes' if ctx.get('sensitive_data') else 'No'}"),
                  st["body"]),
        Paragraph("Risk score = CVSS base score adjusted for internet exposure, data "
                  "sensitivity and business criticality (capped at 10). Priority: P1 &gt;= 9.0, "
                  "P2 &gt;= 7.0, P3 &gt;= 4.0, P4 below 4.0. Detection confidence is reported "
                  "separately.", st["small"]),
        Paragraph("3. Assessment coverage", st["h2"]),
    ]
    cov = [[P("Host:port"), P("Service"), P("Product / version"), P("Status")]]
    for c in coverage_rows(r):
        cov.append([P(f"{c['host']}:{c['port']}/{c['protocol']}"), P(c["service"]),
                    P((c["product"] + " " + c["version"]).strip() or "-"),
                    P("Assessed" if c["assessed"] else f"Not assessed: {c['reason']}")])
    ct = Table(cov, colWidths=[38 * mm, 28 * mm, 40 * mm, 64 * mm], repeatRows=1)
    ct.setStyle(grid)
    story.append(ct)

    story.append(Paragraph("4. Findings and recommendations", st["h2"]))
    findings = flat_findings(r)
    if findings:
        summary_rows = [[P("#"), P("Priority"), P("CVE"), P("Target"), P("CVSS"),
                         P("Risk"), P("Confidence")]]
        for n, f in enumerate(findings, 1):
            summary_rows.append([P(n), P(f["priority"]), P(f["id"]),
                                 P(f"{f['host']}:{f['port']}"),
                                 P(f"{f['cvss']} {f['severity'].capitalize()}"),
                                 P(f["risk_score"]), P(f["confidence"])])
        stbl = Table(summary_rows, colWidths=[8 * mm, 16 * mm, 34 * mm, 38 * mm, 28 * mm,
                                              14 * mm, 22 * mm], repeatRows=1)
        style = TableStyle(grid.getCommands())
        for i, f in enumerate(findings, 1):
            style.add("TEXTCOLOR", (1, i), (1, i), colors.HexColor(PRIO_HEX.get(f["priority"], "#000000")))
        stbl.setStyle(style)
        story += [stbl, Spacer(1, 4 * mm)]

        for n, f in enumerate(findings, 1):
            m = f["mitigation"]
            block = [
                Paragraph(f"<b>{n}. {_e(f['id'])}</b> &nbsp; "
                          f"<font color='{PRIO_HEX.get(f['priority'], '#000000')}'>"
                          f"<b>{_e(f['priority'])}</b></font> &nbsp; "
                          f"<font color='{SEV_HEX.get(f['severity'], '#000000')}'>"
                          f"{_e(_cvss_label(f))}</font>",
                          st["body"]),
                Paragraph(_e(f"{f['host']}:{f['port']}/{f['protocol']} | {_service_label(f)} | "
                             f"risk {f['risk_score']}/10 | confidence {f['confidence']}"
                             + (" (keyword match)" if f["match_method"] == "keyword" else "")),
                          st["small"]),
                Paragraph(_e(f["description"]), st["body"]),
                Paragraph("<b>Recommendation:</b> " + _e(m["summary"]), st["body"]),
            ]
            for i, step in enumerate(m["steps"], 1):
                block.append(Paragraph(f"&nbsp;&nbsp;{i}. {_e(step)}", st["body"]))
            block.append(Paragraph(_e(source_text(m) + " | "
                                      + " ".join(m["references"])), st["small"]))
            block.append(Spacer(1, 4 * mm))
            story.append(KeepTogether(block))
    else:
        story.append(Paragraph("No findings.", st["body"]))

    story += [Spacer(1, 6 * mm), Paragraph(_e(DISCLAIMER), st["small"])]

    def on_page(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(colors.HexColor("#5b6470"))
        canvas.drawString(18 * mm, 10 * mm, f"CONFIDENTIAL | VulnScan report {scan['id']}")
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(path, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=18 * mm,
                            title=f"Vulnerability Assessment Report - {scan['target']}",
                            author="VulnScan")
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
